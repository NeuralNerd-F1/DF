"""Declarative base, deterministic constraint naming, and dialect-portable column types.

The persistence layer must run in two worlds from ONE set of models:
- **PostgreSQL** (deploy + the marked migration test) — native ``JSONB`` / ``TEXT[]`` / ``UUID`` /
  ``ENUM`` (master §9: "JSONB for vectors and SHAP arrays").
- **SQLite via aiosqlite** (the whole offline unit suite) — no native JSONB/ARRAY/ENUM, so the same
  columns compile to ``JSON`` / ``JSON`` / ``CHAR(32)`` / ``VARCHAR + CHECK``.

``.with_variant`` single-sources each type so ``Base.metadata.create_all()`` works on SQLite while
Alembic still emits Postgres-native DDL. The naming convention makes autogenerated constraint names
deterministic — that is what lets the "migration ≡ metadata / no drift" test mean something.
"""

from __future__ import annotations

import uuid
from typing import Any

import sqlalchemy as sa
from sqlalchemy import JSON, MetaData, Text
from sqlalchemy.dialects.postgresql import ARRAY, JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Deterministic constraint/index names (SQLAlchemy naming convention). Without this, Alembic
# autogenerate would invent names and the no-drift guard test could never converge.
NAMING_CONVENTION: dict[str, str] = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Declarative base for every APEX table, carrying the shared naming convention.

    Schema-agnostic by design: ``database.schema_name`` (§12.2 ``apex_schema``) is applied at the
    Alembic/engine layer, not baked into the models, so the SQLite unit suite (which has no schemas)
    uses exactly the same model definitions as a shared-instance Postgres deploy.
    """

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


# --- Dialect-portable column types (Postgres-native / SQLite-fallback) --------------------------
# Shared TypeEngine instances (SQLAlchemy types are designed to be reused across columns).
JSONB_VARIANT = JSONB().with_variant(JSON(), "sqlite")
"""``JSONB`` on PostgreSQL, ``JSON`` on SQLite — for feature vectors, SHAP arrays, radar, flags."""

TEXT_ARRAY_VARIANT = ARRAY(Text()).with_variant(JSON(), "sqlite")
"""``TEXT[]`` on PostgreSQL, a ``JSON`` list on SQLite — for ``lap_features.imputed_features``."""


def uuid_pk() -> Mapped[uuid.UUID]:
    """A UUID primary key, generated app-side (``uuid4``) so ids exist before flush.

    ``sa.Uuid`` maps to native ``UUID`` on PostgreSQL and ``CHAR(32)`` on SQLite — one column
    definition, both dialects.
    """
    return mapped_column(sa.Uuid(), primary_key=True, default=uuid.uuid4)


def pg_enum(enum_cls: type[Any], name: str) -> sa.Enum:
    """A native PostgreSQL ``ENUM`` (VARCHAR + CHECK on SQLite) that stores the member ``.value``.

    ``values_callable`` is mandatory: without it SQLAlchemy would persist enum *names*, which differ
    from values for e.g. ``CircuitType.STREET == "street"`` — and the whole codebase stores StrEnum
    ``.value`` strings (errors.py: "Members serialise to their string value"). This keeps the DB
    domain byte-identical to what the app emits (divergence #25).
    """
    return sa.Enum(
        enum_cls,
        name=name,
        values_callable=lambda e: [str(m.value) for m in e],
        native_enum=True,
        # Fail-loud on BOTH dialects (non-negotiable #1): validate_strings rejects an out-of-domain
        # value at bind time (any dialect); create_constraint emits a CHECK on the non-native
        # (SQLite) variant. Postgres's native ENUM enforces the domain on its own.
        validate_strings=True,
        create_constraint=True,
    )
