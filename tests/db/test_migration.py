"""Alembic migration: upgrade/downgrade round-trip + models≡migration (no drift).

``command.upgrade``/``downgrade`` drive the async env via ``asyncio.run`` internally, so these are
**sync** tests. The whole thing runs offline on a temp-file SQLite DB (``:memory:`` can't be shared
across Alembic's own connection). The same round-trip + no-drift check runs against real PostgreSQL
under ``@pytest.mark.postgres`` when ``APEX_TEST_DATABASE_URL`` is set.
"""

from __future__ import annotations

import os
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from app.contracts.config import ConfigError
from sqlalchemy import create_engine, inspect

APEX_TABLES = {
    "drivers",
    "circuits",
    "sessions",
    "laps",
    "lap_features",
    "fingerprints",
    "predictions",
    "setup_recommendations",
    "degradation_alerts",
    "data_quality_log",
}


def _alembic_cfg() -> Config:
    cfg = Config("alembic.ini")
    cfg.set_main_option("script_location", "migrations")
    return cfg


def _table_names(sync_url: str) -> set[str]:
    engine = create_engine(sync_url)
    try:
        return set(inspect(engine).get_table_names())
    finally:
        engine.dispose()


# --- offline (SQLite) --------------------------------------------------------------------------
def test_upgrade_creates_all_ten_tables(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    db_file = tmp_path / "apex.db"
    monkeypatch.setenv("APEX_DATABASE_URL", f"sqlite+aiosqlite:///{db_file}")
    command.upgrade(_alembic_cfg(), "head")
    tables = _table_names(f"sqlite:///{db_file}")
    assert APEX_TABLES <= tables
    assert "alembic_version" in tables


def test_downgrade_removes_all_apex_tables(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    db_file = tmp_path / "apex.db"
    monkeypatch.setenv("APEX_DATABASE_URL", f"sqlite+aiosqlite:///{db_file}")
    cfg = _alembic_cfg()
    command.upgrade(cfg, "head")
    command.downgrade(cfg, "base")
    tables = _table_names(f"sqlite:///{db_file}")
    assert not (APEX_TABLES & tables)  # every APEX table dropped


def test_no_autogenerate_drift(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """`alembic check` after upgrade must detect no pending operations — models ≡ migration."""
    db_file = tmp_path / "apex.db"
    monkeypatch.setenv("APEX_DATABASE_URL", f"sqlite+aiosqlite:///{db_file}")
    cfg = _alembic_cfg()
    command.upgrade(cfg, "head")
    command.check(cfg)  # raises AutogenerateDiffsDetected on drift


def test_offline_sql_mode_is_unsupported(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The create_all baseline needs a live connection — `--sql` offline mode fails loud."""
    db_file = tmp_path / "apex.db"
    monkeypatch.setenv("APEX_DATABASE_URL", f"sqlite+aiosqlite:///{db_file}")
    with pytest.raises(ConfigError):  # env.py refuses offline mode explicitly
        command.upgrade(_alembic_cfg(), "head", sql=True)


# --- online (PostgreSQL) — skipped unless APEX_TEST_DATABASE_URL is set -------------------------
@pytest.mark.postgres
def test_postgres_migration_roundtrip_and_no_drift(monkeypatch: pytest.MonkeyPatch) -> None:
    test_dsn = os.environ.get("APEX_TEST_DATABASE_URL")
    if not test_dsn:
        pytest.skip("APEX_TEST_DATABASE_URL not set — real-Postgres migration test skipped")
    monkeypatch.setenv("APEX_DATABASE_URL", test_dsn)
    cfg = _alembic_cfg()
    command.upgrade(cfg, "head")
    try:
        assert APEX_TABLES <= _table_names(test_dsn)
        command.check(cfg)  # native JSONB/ENUM/UUID schema matches the models — no drift
    finally:
        command.downgrade(cfg, "base")
    assert not (APEX_TABLES & _table_names(test_dsn))
